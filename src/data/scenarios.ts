export function scoreScenario(choice: ScenarioChoice, ticked: ChecklistId[], scenario: Scenario) {
  const rec = scenario.recommendedChecklist;
  const checklistScore = rec.length ? Math.round((rec.filter((id) => ticked.includes(id)).length / rec.length) * 100) : 100;
  const score = choice.unsafe ? 0 : Math.round(choice.score * 0.8 + checklistScore * 0.2);
  return { choiceScore: choice.score, checklistScore, score, unsafe: !!choice.unsafe };
}
